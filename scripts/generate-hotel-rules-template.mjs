function sectionTitle(text) {
  return para([txt(text, { size: SZ_SECTION, bold: true, color: ACCENT })], {
    align: AlignmentType.LEFT,
    before: 90,
    after: 35,
  });
}

function point(num, text) {
  return para([txt(`${num}. `, { bold: true }), txt(text)], { after: 30 });
}

